    /**
     * Configuración del JTable de detalle.
     * Qué hace: Define columnas y bloquea edición de celdas (consulta de solo lectura).
     */
    private void inicializarDetalle() {
        modeloDetalle = new DefaultTableModel(
            new Object[]{"Código", "Descripción", "Precio Unit.", "Cantidad", "Importe"}, 0
        ) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false; // Solo lectura
            }
        };
        tblDetalle.setModel(modeloDetalle);
    }

    /**
     * Carga la factura completa desde la base de datos.
     * Qué hace: Puebla los campos de encabezado y llena el JTable con los productos vendidos.
     * Cómo lo hace:
     * 1. Llama a facturaDAO.obtener(numero) y coloca N°, fecha, cédula, cliente y total en los campos.
     * 2. Llama a facturaDAO.listarDetalle(numero) y agrega cada línea al modelo del JTable.
     */
    private void cargarFactura(int numero) {
        try {
            // Carga de datos de encabezado
            Factura f = facturaDAO.obtener(numero);
            if (f != null) {
                txtNumeroFactura.setText(String.valueOf(f.getNumero()));
                txtFecha.setText(f.getFecha() != null ? f.getFecha().toString() : "");
                txtCedula.setText(f.getCedulaCliente());
                txtCliente.setText(f.getNombreCliente());
                txtTotal.setText("₡ " + String.format("%.2f", f.getTotal()));
            }

            // Carga de líneas del detalle
            modeloDetalle.setRowCount(0);
            List<DetalleFactura> detalle = facturaDAO.listarDetalle(numero);
            for (DetalleFactura d : detalle) {
                modeloDetalle.addRow(new Object[]{
                    d.getCodigoProducto(),
                    d.getDescripcion(),
                    d.getPrecio(),
                    d.getCantidad(),
                    String.format("%.2f", d.getImporte())
                });
            }
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, ErrorBD.mensaje(ex), "Error al consultar factura", JOptionPane.ERROR_MESSAGE);
        }
    }

