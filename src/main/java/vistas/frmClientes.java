    /**
     * Evento al hacer clic en una fila del JTable.
     * Qué hace: Pasa la información del cliente a los campos de edición.
     * Cómo lo hace: Extrae valores por índice de columna de modeloTabla y bloquea
     * la cédula para proteger la clave primaria durante la actualización.
     */
    private void tblClientesMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblClientesMouseClicked
        int fila = tblClientes.getSelectedRow();
        if (fila >= 0) {
            txtCedula.setText(String.valueOf(modeloTabla.getValueAt(fila, 0)));
            txtNombre.setText(String.valueOf(modeloTabla.getValueAt(fila, 1)));
            txtTelefono.setText(String.valueOf(modeloTabla.getValueAt(fila, 2)));
            txtCorreo.setText(String.valueOf(modeloTabla.getValueAt(fila, 3)));
            txtCedula.setEditable(false); // Clave primaria inmutable en modificación
        }
    }//GEN-LAST:event_tblClientesMouseClicked

    /**
     * Acción del botón Agregar.
     * Qué hace: Guarda un nuevo cliente en la base de datos.
     * Cómo lo hace: Valida campos obligatorios, llama a clienteDAO.insertar(),
     * notifica éxito, limpia campos y recarga la tabla.
     */
    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
        try {
            String cedula = txtCedula.getText().trim();
            String nombre = txtNombre.getText().trim();
            String tel = txtTelefono.getText().trim();
            String correo = txtCorreo.getText().trim();

            if (cedula.isEmpty() || nombre.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Debe completar al menos cédula y nombre.", "Aviso", JOptionPane.WARNING_MESSAGE);
                return;
            }

            clienteDAO.insertar(new Cliente(cedula, nombre, tel, correo));
            JOptionPane.showMessageDialog(this, "Cliente agregado correctamente.");
            limpiar();
            cargarDatos("");
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, ErrorBD.mensaje(ex), "Error al agregar cliente", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnAgregarActionPerformed

    /**
     * Acción del botón Guardar cambios.
     * Qué hace: Modifica un cliente previamente seleccionado.
     * Cómo lo hace: Envía los campos actualizados mediante clienteDAO.actualizar(),
     * confirma el cambio y actualiza el JTable.
     */
    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        try {
            String cedula = txtCedula.getText().trim();
            String nombre = txtNombre.getText().trim();
            String tel = txtTelefono.getText().trim();
            String correo = txtCorreo.getText().trim();

            if (cedula.isEmpty() || nombre.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Seleccione un cliente para modificar.", "Aviso", JOptionPane.WARNING_MESSAGE);
                return;
            }

            clienteDAO.actualizar(new Cliente(cedula, nombre, tel, correo));
            JOptionPane.showMessageDialog(this, "Cliente actualizado correctamente.");
            limpiar();
            cargarDatos("");
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, ErrorBD.mensaje(ex), "Error al actualizar", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

    /**
     * Acción del botón Eliminar.
     * Qué hace: Borra al cliente seleccionado de MySQL.
     * Cómo lo hace: Solicita confirmación y llama a clienteDAO.eliminar(cedula).
     * Si el cliente tiene facturas asociadas, captura el error de clave foránea.
     */
    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        String cedula = txtCedula.getText().trim();
        if (cedula.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Seleccione un cliente de la tabla.", "Aviso", JOptionPane.WARNING_MESSAGE);
            return;
        }

        int resp = JOptionPane.showConfirmDialog(this, "¿Desea eliminar al cliente " + cedula + "?", "Confirmar eliminación", JOptionPane.YES_NO_OPTION);
        if (resp == JOptionPane.YES_OPTION) {
            try {
                clienteDAO.eliminar(cedula);
                JOptionPane.showMessageDialog(this, "Cliente eliminado.");
                limpiar();
                cargarDatos("");
            } catch (SQLException ex) {
                JOptionPane.showMessageDialog(this, ErrorBD.mensaje(ex), "Error al eliminar", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

