    /**
     * Configuración del JTable.
     * Qué hace: Define las 4 columnas de clientes e impide la edición directa de celdas.
     * Cómo lo hace: Sobrescribe isCellEditable() retornando false.
     */
    private void inicializarTabla() {
        modeloTabla = new DefaultTableModel(
            new Object[]{"Cédula", "Nombre", "Teléfono", "Correo"}, 0
        ) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false; // Edición controlada exclusivamente desde el formulario inferior
            }
        };
        tblClientes.setModel(modeloTabla);
    }

    /**
     * Carga o filtra los clientes en el JTable.
     * Qué hace: Refresca el contenido de la tabla con los datos de MySQL.
     * Cómo lo hace: Limpia filas anteriores con setRowCount(0), invoca clienteDAO.buscar(filtro)
     * e inserta cada registro en el modelo.
     */
    private void cargarDatos(String filtro) {
        modeloTabla.setRowCount(0);
        try {
            List<Cliente> lista = clienteDAO.buscar(filtro);
            for (Cliente c : lista) {
                modeloTabla.addRow(new Object[]{
                    c.getCedula(),
                    c.getNombre(),
                    c.getTelefono(),
                    c.getCorreo()
                });
            }
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, ErrorBD.mensaje(ex), "Error al cargar clientes", JOptionPane.ERROR_MESSAGE);
        }
    }

    /**
     * Limpia los campos del formulario.
     * Qué hace: Vacía las cajas de texto y permite ingresar un nuevo cliente.
     * Cómo lo hace: Reestablece el texto a vacío, habilita la edición de la cédula y deselecciona la tabla.
     */
    private void limpiar() {
        txtCedula.setText("");
        txtNombre.setText("");
        txtTelefono.setText("");
        txtCorreo.setText("");
        txtCedula.setEditable(true); // Permite escribir una nueva cédula
        tblClientes.clearSelection();
    }

