    /**
     * Configuración del JTable.
     * Qué hace: Define las columnas Cédula y Nombre, y protege las celdas de edición directa.
     * Cómo lo hace: Sobrescribe isCellEditable() retornando false.
     */
    private void inicializarTabla() {
        modeloTabla = new DefaultTableModel(
            new Object[]{"Cédula", "Nombre"}, 0
        ) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false; // La edición se hace exclusivamente mediante los campos de abajo
            }
        };
        tblUsuarios.setModel(modeloTabla);
    }

    /**
     * Carga o filtra los usuarios en el JTable.
     * Qué hace: Muestra los usuarios activos devueltos por la base de datos.
     * Cómo lo hace: Limpia filas anteriores con setRowCount(0), invoca usuarioDAO.buscar(filtro)
     * e inserta cada usuario en el modelo (sin exponer contraseñas en la tabla).
     */
    private void cargarDatos(String filtro) {
        modeloTabla.setRowCount(0);
        try {
            List<Usuario> lista = usuarioDAO.buscar(filtro);
            for (Usuario u : lista) {
                modeloTabla.addRow(new Object[]{
                    u.getCedula(),
                    u.getNombre()
                });
            }
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, ErrorBD.mensaje(ex), "Error al cargar usuarios", JOptionPane.ERROR_MESSAGE);
        }
    }

    /**
     * Limpia los campos del formulario.
     * Qué hace: Vacía las cajas de texto y permite crear un nuevo usuario.
     * Cómo lo hace: Limpia cédula, nombre y contraseña, habilita la edición de cédula y limpia selección.
     */
    private void limpiar() {
        txtCedula.setText("");
        txtNombre.setText("");
        txtContrasena.setText("");
        txtCedula.setEditable(true); // Permite ingresar una nueva cédula
        tblUsuarios.clearSelection();
    }

