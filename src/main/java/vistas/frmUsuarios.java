    /**
     * Evento al hacer clic en una fila del JTable.
     * Qué hace: Carga los datos del usuario en los campos para editar o borrar.
     * Cómo lo hace: Lee la cédula y nombre de la fila seleccionada y bloquea el campo cédula.
     */
    private void tblUsuariosMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblUsuariosMouseClicked
        int fila = tblUsuarios.getSelectedRow();
        if (fila >= 0) {
            txtCedula.setText(String.valueOf(modeloTabla.getValueAt(fila, 0)));
            txtNombre.setText(String.valueOf(modeloTabla.getValueAt(fila, 1)));
            txtCedula.setEditable(false); // Llave primaria protegida contra edición
        }
    }//GEN-LAST:event_tblUsuariosMouseClicked

    /**
     * Acción del botón Agregar.
     * Qué hace: Registra un nuevo usuario con credenciales en MySQL.
     * Cómo lo hace: Comprueba cédula, nombre y contraseña, invoca usuarioDAO.insertar(),
     * notifica confirmación, limpia campos y actualiza la tabla.
     */
    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
        try {
            String cedula = txtCedula.getText().trim();
            String nombre = txtNombre.getText().trim();
            String pass = new String(txtContrasena.getPassword()).trim();

            if (cedula.isEmpty() || nombre.isEmpty() || pass.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Debe completar cédula, nombre y contraseña.", "Aviso", JOptionPane.WARNING_MESSAGE);
                return;
            }

            usuarioDAO.insertar(new Usuario(cedula, nombre, pass));
            JOptionPane.showMessageDialog(this, "Usuario registrado correctamente.");
            limpiar();
            cargarDatos("");
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, ErrorBD.mensaje(ex), "Error al registrar usuario", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnAgregarActionPerformed

    /**
     * Acción del botón Guardar cambios.
     * Qué hace: Actualiza nombre y/o contraseña de un usuario existente.
     * Cómo lo hace: Invoca usuarioDAO.actualizar() con los nuevos valores ingresados.
     */
    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        try {
            String cedula = txtCedula.getText().trim();
            String nombre = txtNombre.getText().trim();
            String pass = new String(txtContrasena.getPassword()).trim();

            if (cedula.isEmpty() || nombre.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Seleccione un usuario para modificar.", "Aviso", JOptionPane.WARNING_MESSAGE);
                return;
            }

            usuarioDAO.actualizar(new Usuario(cedula, nombre, pass));
            JOptionPane.showMessageDialog(this, "Usuario actualizado correctamente.");
            limpiar();
            cargarDatos("");
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, ErrorBD.mensaje(ex), "Error al actualizar", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

    /**
     * Acción del botón Eliminar.
     * Qué hace: Elimina un usuario del sistema.
     * Cómo lo hace: Solicita confirmación y ejecuta usuarioDAO.eliminar(cedula).
     */
    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        String cedula = txtCedula.getText().trim();
        if (cedula.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Seleccione un usuario de la tabla.", "Aviso", JOptionPane.WARNING_MESSAGE);
            return;
        }

        int resp = JOptionPane.showConfirmDialog(this, "¿Desea eliminar al usuario " + cedula + "?", "Confirmar eliminación", JOptionPane.YES_NO_OPTION);
        if (resp == JOptionPane.YES_OPTION) {
            try {
                usuarioDAO.eliminar(cedula);
                JOptionPane.showMessageDialog(this, "Usuario eliminado.");
                limpiar();
                cargarDatos("");
            } catch (SQLException ex) {
                JOptionPane.showMessageDialog(this, ErrorBD.mensaje(ex), "Error al eliminar", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

