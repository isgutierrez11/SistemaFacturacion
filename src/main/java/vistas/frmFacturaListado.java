    /**
     * Acción del botón Ver factura.
     * Qué hace: Abre la pantalla de consulta detallada de la factura seleccionada.
     * Cómo lo hace: Obtiene el número de factura de la fila seleccionada en tblFacturas
     * y se lo pasa como parámetro al constructor de frmFacturaConsulta(numero).
     */
    private void btnVerFacturaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnVerFacturaActionPerformed
        int fila = tblFacturas.getSelectedRow();
        if (fila < 0) {
            JOptionPane.showMessageDialog(this, "Seleccione una factura de la tabla para ver el detalle.", "Aviso", JOptionPane.WARNING_MESSAGE);
            return;
        }

        // Obtiene el número de factura de la primera columna
        int numero = Integer.parseInt(String.valueOf(modeloTabla.getValueAt(fila, 0)));
        new frmFacturaConsulta(numero).setVisible(true);
        this.dispose();
    }//GEN-LAST:event_btnVerFacturaActionPerformed

