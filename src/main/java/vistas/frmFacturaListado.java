    /**
     * Configuración del JTable.
     * Qué hace: Establece las 5 columnas del listado de facturas y protege las celdas contra edición.
     * Cómo lo hace: Sobrescribe isCellEditable() retornando false.
     */
    private void inicializarTabla() {
        modeloTabla = new DefaultTableModel(
            new Object[]{"N° Factura", "Fecha", "Cédula", "Cliente", "Total"}, 0
        ) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false; // Tabla de solo visualización
            }
        };
        tblFacturas.setModel(modeloTabla);
    }

    /**
     * Carga o filtra el listado de facturas en el JTable.
     * Qué hace: Llena la tabla con los encabezados devueltos por la base de datos.
     * Cómo lo hace: Limpia filas anteriores con setRowCount(0), invoca facturaDAO.listar(filtro)
     * y agrega cada factura con su formato monetario.
     */
    private void cargarDatos(String filtro) {
        modeloTabla.setRowCount(0);
        try {
            List<Factura> lista = facturaDAO.listar(filtro);
            for (Factura f : lista) {
                modeloTabla.addRow(new Object[]{
                    f.getNumero(),
                    f.getFecha(),
                    f.getCedulaCliente(),
                    f.getNombreCliente(),
                    "₡ " + String.format("%.2f", f.getTotal())
                });
            }
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, ErrorBD.mensaje(ex), "Error al cargar facturas", JOptionPane.ERROR_MESSAGE);
        }
    }

