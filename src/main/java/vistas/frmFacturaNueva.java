    /**
     * Acción del botón Buscar Cliente.
     * Qué hace: Localiza al cliente por su cédula para asociarlo a la factura.
     * Cómo lo hace: Consulta clienteDAO.buscarPorCedula(cedula) y, si existe, coloca su nombre
     * en txtNombreCliente de manera automática.
     */
    private void btnBuscarClienteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarClienteActionPerformed
        String cedula = txtCedulaCliente.getText().trim();
        if (cedula.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Escriba la cédula del cliente a buscar.", "Aviso", JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            Cliente c = clienteDAO.buscarPorCedula(cedula);
            if (c != null) {
                txtNombreCliente.setText(c.getNombre());
            } else {
                txtNombreCliente.setText("");
                JOptionPane.showMessageDialog(this, "Cliente no encontrado. Verifique la cédula o regístrelo en Mantenimiento de Clientes.", "No encontrado", JOptionPane.INFORMATION_MESSAGE);
            }
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, ErrorBD.mensaje(ex), "Error al buscar cliente", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnBuscarClienteActionPerformed

