    /**
     * Configuración del JTable de detalle.
     * Qué hace: Establece las columnas (Código, Descripción, Precio Unit., Cantidad, Importe).
     * Cómo lo hace: Sobrescribe isCellEditable() para evitar alteraciones directas no calculadas.
     */
    private void inicializarDetalle() {
        modeloDetalle = new DefaultTableModel(
            new Object[]{"Código", "Descripción", "Precio Unit.", "Cantidad", "Importe"}, 0
        ) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };
        tblDetalle.setModel(modeloDetalle);
    }

    /**
     * Carga el encabezado inicial.
     * Qué hace: Consulta el próximo número de factura disponible y coloca la fecha actual del sistema.
     * Cómo lo hace: Llama a facturaDAO.siguienteNumero() y usa LocalDate.now().
     */
    private void cargarEncabezadoInicial() {
        try {
            int siguiente = facturaDAO.siguienteNumero();
            txtNumeroFactura.setText(String.valueOf(siguiente));
        } catch (SQLException ex) {
            txtNumeroFactura.setText("1");
        }
        txtFecha.setText(LocalDate.now().toString());
    }

    /**
     * Recalcula el total de la factura.
     * Qué hace: Suma los importes de todas las líneas añadidas al JTable de detalle.
     * Cómo lo hace: Recorre las filas, extrae la columna 4 (Importe), suma a totalGeneral y formatea el texto.
     */
    private void recalcularTotal() {
        totalGeneral = 0.0;
        for (int i = 0; i < modeloDetalle.getRowCount(); i++) {
            double imp = Double.parseDouble(String.valueOf(modeloDetalle.getValueAt(i, 4)));
            totalGeneral += imp;
        }
        txtTotal.setText("₡ " + String.format("%.2f", totalGeneral));
    }

    /**
     * Limpia todo el formulario.
     * Qué hace: Restablece campos de cliente, producto, detalle y reinicia el total a cero.
     */
    private void limpiarFormulario() {
        txtCedulaCliente.setText("");
        txtNombreCliente.setText("");
        txtCodigoProducto.setText("");
        txtDescripcionProducto.setText("");
        txtPrecioUnitario.setText("");
        txtCantidad.setText("");
        txtImporte.setText("");
        modeloDetalle.setRowCount(0);
        recalcularTotal();
        cargarEncabezadoInicial();
    }

