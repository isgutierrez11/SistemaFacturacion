    /**
     * Evento al hacer clic sobre una fila del JTable.
     * Qué hace: Traslada los datos de la fila seleccionada a los campos inferiores para editar o eliminar.
     * Cómo lo hace: Obtiene el índice con getSelectedRow(), lee los valores de modeloTabla y
     * bloquea el campo de código (llave primaria no editable durante modificación).
     */
    private void tblProductosMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblProductosMouseClicked
        int fila = tblProductos.getSelectedRow();
        if (fila >= 0) {
            txtCodigo.setText(String.valueOf(modeloTabla.getValueAt(fila, 0)));
            txtDescripcion.setText(String.valueOf(modeloTabla.getValueAt(fila, 1)));
            txtPrecio.setText(String.valueOf(modeloTabla.getValueAt(fila, 2)));
            txtExistencia.setText(String.valueOf(modeloTabla.getValueAt(fila, 3)));
            txtCodigo.setEditable(false); // Llave primaria bloqueada en edición
        }
    }//GEN-LAST:event_tblProductosMouseClicked

    /**
     * Acción del botón Agregar.
     * Qué hace: Registra un nuevo producto en MySQL.
     * Cómo lo hace: Valida campos requeridos, convierte precio a double y existencia a int,
     * ejecuta productoDAO.insertar(), limpia el formulario y recarga la tabla.
     */
    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
        try {
            String codigo = txtCodigo.getText().trim();
            String desc = txtDescripcion.getText().trim();
            double precio = Double.parseDouble(txtPrecio.getText().trim());
            int stock = Integer.parseInt(txtExistencia.getText().trim());

            if (codigo.isEmpty() || desc.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Debe completar todos los campos.", "Aviso", JOptionPane.WARNING_MESSAGE);
                return;
            }

            productoDAO.insertar(new Producto(codigo, desc, precio, stock));
            JOptionPane.showMessageDialog(this, "Producto agregado correctamente.");
            limpiar();
            cargarDatos("");
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Precio debe ser decimal y Existencia entero.", "Formato inválido", JOptionPane.WARNING_MESSAGE);
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, ErrorBD.mensaje(ex), "Error al agregar", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnAgregarActionPerformed

    /**
     * Acción del botón Guardar cambios.
     * Qué hace: Actualiza la información de un producto seleccionado.
     * Cómo lo hace: Lee los campos editados, ejecuta productoDAO.actualizar(),
     * notifica el resultado y refresca la tabla.
     */
    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        try {
            String codigo = txtCodigo.getText().trim();
            String desc = txtDescripcion.getText().trim();
            double precio = Double.parseDouble(txtPrecio.getText().trim());
            int stock = Integer.parseInt(txtExistencia.getText().trim());

            if (codigo.isEmpty() || desc.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Seleccione un producto para modificar.", "Aviso", JOptionPane.WARNING_MESSAGE);
                return;
            }

            productoDAO.actualizar(new Producto(codigo, desc, precio, stock));
            JOptionPane.showMessageDialog(this, "Producto actualizado correctamente.");
            limpiar();
            cargarDatos("");
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Precio debe ser decimal y Existencia entero.", "Formato inválido", JOptionPane.WARNING_MESSAGE);
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, ErrorBD.mensaje(ex), "Error al guardar", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

    /**
     * Acción del botón Eliminar.
     * Qué hace: Remueve un producto de la base de datos.
     * Cómo lo hace: Pide confirmación al usuario, llama a productoDAO.eliminar(codigo)
     * y maneja restricciones de integridad referencial si está asociado a facturas.
     */
    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        String codigo = txtCodigo.getText().trim();
        if (codigo.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Seleccione un producto de la tabla.", "Aviso", JOptionPane.WARNING_MESSAGE);
            return;
        }

        int resp = JOptionPane.showConfirmDialog(this, "¿Desea eliminar el producto " + codigo + "?", "Confirmar eliminación", JOptionPane.YES_NO_OPTION);
        if (resp == JOptionPane.YES_OPTION) {
            try {
                productoDAO.eliminar(codigo);
                JOptionPane.showMessageDialog(this, "Producto eliminado.");
                limpiar();
                cargarDatos("");
            } catch (SQLException ex) {
                JOptionPane.showMessageDialog(this, ErrorBD.mensaje(ex), "Error al eliminar", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

