    /**
     * Configuración del JTable.
     * Qué hace: Define las columnas de la tabla y deshabilita la edición directa en las celdas.
     * Cómo lo hace: Sobrescribe isCellEditable() retornando false.
     */
    private void inicializarTabla() {
        modeloTabla = new DefaultTableModel(
            new Object[]{"Código", "Descripción", "Precio", "Existencia"}, 0
        ) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false; // Solo lectura en la tabla; se edita mediante el formulario inferior
            }
        };
        tblProductos.setModel(modeloTabla);
    }

    /**
     * Carga o filtra los productos en el JTable.
     * Qué hace: Llena la tabla con los registros devueltos por la base de datos.
     * Cómo lo hace: Limpia las filas existentes con setRowCount(0), llama a productoDAO.buscar(filtro)
     * e inserta cada producto como una nueva fila.
     */
    private void cargarDatos(String filtro) {
        modeloTabla.setRowCount(0);
        try {
            List<Producto> lista = productoDAO.buscar(filtro);
            for (Producto p : lista) {
                modeloTabla.addRow(new Object[]{
                    p.getCodigo(),
                    p.getDescripcion(),
                    p.getPrecio(),
                    p.getExistencia()
                });
            }
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, ErrorBD.mensaje(ex), "Error al cargar productos", JOptionPane.ERROR_MESSAGE);
        }
    }

    /**
     * Limpia los campos del formulario.
     * Qué hace: Restablece los campos de texto y prepara el formulario para un nuevo registro.
     * Cómo lo hace: Vacía el texto, reactiva la edición del campo código y quita la selección del JTable.
     */
    private void limpiar() {
        txtCodigo.setText("");
        txtDescripcion.setText("");
        txtPrecio.setText("");
        txtExistencia.setText("");
        txtCodigo.setEditable(true); // Permite ingresar una nueva llave primaria
        tblProductos.clearSelection();
    }

